import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) {
  test(`company search opens sourced company records and resets at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    const toggle = page.locator('.desk-company-search>summary')
    await expect(toggle).toBeVisible()
    expect((await toggle.boundingBox())!.y).toBeLessThan(width === 390 ? 844 : 900)
    await toggle.focus()
    await page.keyboard.press('Enter')
    const search = page.getByRole('search', { name: 'Company search' })
    const field = search.getByRole('searchbox', { name: 'Search for a company' })
    await expect(field).toBeVisible()
    await field.fill('  vArOnIs  ')
    await expect(search.getByRole('status')).toHaveText('1 matching record.')
    const result = search.getByRole('button', { name: 'Varonis Systems VRNS' })
    await result.focus()
    await page.keyboard.press('Enter')
    const record = page.getByRole('dialog', { name: 'Varonis Systems, Inc.' })
    await expect(record).toBeVisible()
    const agreement = record.locator('.desk-dialog__events li').filter({ hasText: 'Proofpoint to acquire Varonis' })
    await expect(agreement).toContainText('2026-10-15')
    await expect(agreement.locator('a')).toHaveAttribute('href', 'https://www.proofpoint.com/us/newsroom/press-releases/proofpoint-acquire-varonis-creating-global-leader-data-and-ai-security')
    await page.keyboard.press('Escape')
    await expect(result).toBeFocused()
    await field.fill('panw')
    await expect(search.getByRole('button', { name: 'Palo Alto Networks PANW' })).toBeVisible()
    await field.fill('Arctic Wolf Networks')
    await expect(search.getByRole('status')).toHaveText('1 matching record.')
    await field.fill('not-a-tracked-company-123')
    await expect(search.getByRole('status')).toHaveText('0 matching records.')
    await expect(search).toContainText('The roster does not cover every security company.')
    await search.getByRole('button', { name: 'Clear search' }).click()
    await expect(field).toHaveValue('')
    await expect(field).toBeFocused()
    await expect(search.locator('li')).toHaveCount(0)
    await expect(page.locator('.desk-change').first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    expect(errors).toEqual([])
  })
}
